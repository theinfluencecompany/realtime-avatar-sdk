#!/usr/bin/env node
/**
 * Materialize the platform's error semantics from the vendored public contract.
 *
 * WHY THIS EXISTS. `Error.code` is deliberately not an enum in the OpenAPI document, so
 * `openapi-typescript` gives this repo a `string` and nothing more. A caller who wants to act
 * on a failure needs three further facts — which statuses a code may accompany, what to tell a
 * user, and whether retrying is worth it — and none of them survive that generation step. So
 * they were written out by hand here, and they drifted.
 *
 * Measured 2026-09-18 against platform main: `recording_unsupported` on a 501 normalized to
 * `service_unavailable, retryable: true` in this repo. The platform says `retryable: false`,
 * because a recording backend that was never compiled in does not appear on a retry. A
 * published SDK told every caller to retry a permanent refusal forever, and `insufficient_
 * credits` echoed the server's raw `"balance 0"` at users because the hand-written ladder
 * preferred upstream prose over its own copy.
 *
 * The fix is not a better hand-written ladder. It is to stop writing the table twice.
 *
 * WHAT IT WRITES. A single frozen record keyed by code, plus the recognised-but-uncopied list.
 * Values are emitted with `as const` so every key, message, status tuple and retry verdict is a
 * literal type — a consumer can exhaustively switch on a code, and `keyof typeof` is the union
 * rather than a hand-maintained copy of it. Nothing here is hand-edited; `--check` fails the
 * build when the committed file and the vendored spec disagree, the same contract
 * `generate-connection-history.mjs` and `generate-clip-schema.mjs` hold.
 */
import { readFile, writeFile } from "node:fs/promises";

const spec = JSON.parse(await readFile(new URL("../spec/realtime-avatar.openapi.json", import.meta.url), "utf8"));

const semantics = spec["x-error-semantics"];
const codes = semantics?.codes;
const uncopied = spec["x-error-codes-uncopied"];
const shape = spec["x-error-message-shape"];

if (!codes || typeof codes !== "object" || Object.keys(codes).length === 0) {
  throw new Error("error-semantics: x-error-semantics.codes missing from OpenAPI — the platform export must publish it");
}
if (!Array.isArray(uncopied)) {
  throw new Error("error-semantics: x-error-codes-uncopied missing from OpenAPI");
}
if (!shape?.patterns || typeof shape.patterns !== "object" || !Number.isInteger(shape.maxLength)) {
  throw new Error("error-semantics: x-error-message-shape missing or malformed in OpenAPI");
}
for (const [name, pattern] of Object.entries(shape.patterns)) {
  if (typeof pattern?.source !== "string" || typeof pattern?.flags !== "string") {
    throw new Error(`error-semantics: shape pattern '${name}' has no source/flags`);
  }
  // Compile it HERE, at generation time, so an unusable pattern fails the build rather than
  // throwing inside a published bundle the first time a caller sees an error.
  new RegExp(pattern.source, pattern.flags);
}

/**
 * The published table is product copy and retry verdicts, and it arrives over the same channel
 * as everything else in this document. Validate its SHAPE before writing it into source: a
 * malformed entry would otherwise become a type that compiles and a sentence that ships.
 */
for (const [code, entry] of Object.entries(codes)) {
  if (!entry || typeof entry !== "object") throw new Error(`error-semantics: ${code} is not an object`);
  const keys = Object.keys(entry).sort().join(",");
  if (keys !== "message,retryable,statuses") {
    throw new Error(`error-semantics: ${code} has fields [${keys}], expected message,retryable,statuses`);
  }
  if (typeof entry.message !== "string" || !entry.message.trim()) {
    throw new Error(`error-semantics: ${code} has no message`);
  }
  if (typeof entry.retryable !== "boolean") throw new Error(`error-semantics: ${code}.retryable is not a boolean`);
  if (!Array.isArray(entry.statuses) || entry.statuses.length === 0 || !entry.statuses.every((s) => Number.isInteger(s))) {
    throw new Error(`error-semantics: ${code}.statuses is not a non-empty list of integers`);
  }
}
for (const code of uncopied) {
  if (typeof code !== "string" || !code) throw new Error("error-semantics: x-error-codes-uncopied holds a non-string");
  if (code in codes) {
    throw new Error(
      `error-semantics: '${code}' is in BOTH the copy table and the uncopied list. One code, one owner ` +
        `of its sentence — fix it in the platform contract, not here.`,
    );
  }
}

const entry = ([code, value]) =>
  `  ${JSON.stringify(code)}: { statuses: [${value.statuses.join(", ")}], message: ${JSON.stringify(value.message)}, retryable: ${value.retryable} },`;

const body = `// GENERATED by scripts/generate-error-semantics.mjs from spec/realtime-avatar.openapi.json.
// Do not edit. Run \`npm run spec:types\`; \`npm run spec:verify\` fails when this is stale.

/**
 * What a failure code MEANS, published by the platform alongside the shape of the error body.
 *
 * \`statuses\` is the set of HTTP statuses a code may legitimately accompany. A code arriving on
 * any other status is a mismatch and is answered by the status instead — that is what stops a
 * stray code from being read as a refusal the caller could act on.
 */
export const ERROR_SEMANTICS = {
${Object.entries(codes).map(entry).join("\n")}
} as const;

/**
 * Codes the platform recognises whose user-facing sentence is owned elsewhere, because it names
 * a number this table cannot know: a plan's ceiling, an amount owed. Recognised, deliberately
 * uncopied — prefer the server's own \`message\` for these, and never treat them as unknown.
 */
export const UNCOPIED_ERROR_CODES = [
${uncopied.map((code) => `  ${JSON.stringify(code)},`).join("\n")}
] as const;

/** Every code the platform is known to send, copied or not. */
export type KnownErrorCode = keyof typeof ERROR_SEMANTICS | (typeof UNCOPIED_ERROR_CODES)[number];

/** A code whose product copy and retry verdict are published above. */
export type CopiedErrorCode = keyof typeof ERROR_SEMANTICS;

export type ErrorSemantics = (typeof ERROR_SEMANTICS)[CopiedErrorCode];

/**
 * The test for whether an upstream sentence may be repeated to a user verbatim.
 *
 * Shape, never vocabulary. A vocabulary denylist has to name the private stack in order to look
 * for it, and this file ships inside a published bundle — an npm version cannot be withdrawn.
 * This repo reached that conclusion for its own boundary check already; the pattern is now
 * published by the platform so there is only one of it.
 */
const MESSAGE_SHAPE_PATTERNS = ${JSON.stringify(shape.patterns)} as const;

export const MESSAGE_MAX_LENGTH = ${shape.maxLength};

const SHAPE_TESTS = Object.values(MESSAGE_SHAPE_PATTERNS).map(
  (pattern) => new RegExp(pattern.source, pattern.flags),
);

/** True when a backend message must not be repeated to a user verbatim. */
export function hasInternalDetail(message: string): boolean {
  return SHAPE_TESTS.some((pattern) => pattern.test(message));
}

/** Bound and reject upstream prose, or return null when authored copy must be used instead. */
export function userSafeMessage(message: string): string | null {
  const trimmed = message.trim();
  if (!trimmed || hasInternalDetail(trimmed)) return null;
  return trimmed.length > MESSAGE_MAX_LENGTH ? \`\${trimmed.slice(0, MESSAGE_MAX_LENGTH - 3)}...\` : trimmed;
}

/** Narrows a wire string to a key of the table, so indexing needs NO CAST. */
export function isCopiedErrorCode(code: string): code is CopiedErrorCode {
  return Object.hasOwn(ERROR_SEMANTICS, code);
}

/** Whether the platform recognises this code at all, independent of who owns its copy. */
export function isKnownErrorCode(code: string): boolean {
  return isCopiedErrorCode(code) || UNCOPIED_ERROR_CODES.some((known) => known === code);
}

function semanticsFor(code: string): ErrorSemantics | undefined {
  return isCopiedErrorCode(code) ? ERROR_SEMANTICS[code] : undefined;
}

/** The entry a bare status answers with, when no usable code accompanied it. */
function semanticsForStatus(status: number): ErrorSemantics | undefined {
  return Object.values(ERROR_SEMANTICS).find((entry) =>
    entry.statuses.some((allowed) => allowed === status),
  );
}

/** The contract's own name for a status, used when no code accompanied the failure. */
function defaultCodeForStatus(status: number): string {
  const match = Object.entries(ERROR_SEMANTICS).find(([, entry]) =>
    entry.statuses.some((allowed) => allowed === status),
  );
  return match ? match[0] : "request_failed";
}

export type NormalizedError = {
  code: string;
  message: string;
  retryable: boolean;
};

/**
 * THE normalizer. Generated, so the platform and every client run the SAME implementation.
 *
 * This logic existed twice — once in the platform's web surface and once here — and the two
 * had diverged in three measured ways on 2026-09-18 before the table was published. Sharing
 * the TABLE fixed the vocabulary but left two copies of the decision procedure, which is the
 * same defect one level up: the rules about status mismatch and unknown codes are subtle, and
 * two hand-written copies of a subtle rule drift exactly like two hand-written tables do.
 *
 * Three rules, each pinned by a test:
 *   1. A known code on a status it may accompany answers with published copy.
 *   2. A known code on a status it may NOT accompany is DISCARDED, and the status answers.
 *   3. An UNKNOWN code is never promoted to the status default, or an unknown refusal gets
 *      dressed up as a specific one a caller could switch on.
 */
export function normalizeError(
  input: { status?: number; code?: string | null; message?: string | null },
  overrides: { concurrencyLimitFallback: string; requestFailedFallback: string },
): NormalizedError {
  const status = input.status ?? 0;
  const rawCode = input.code?.trim() || null;
  const rawMessage = input.message?.trim() || "";

  if (rawCode) {
    const semantics = semanticsFor(rawCode);
    if (semantics?.statuses.some((allowed) => allowed === status)) {
      return { code: rawCode, message: semantics.message, retryable: semantics.retryable };
    }
  }

  // The three refusals where the SERVER's sentence beats authored copy, because it names a
  // number no table can know: the amount owed, the plan's ceiling, the rejected input.
  if (status === 402) {
    return {
      code: rawCode === "insufficient_credits" || rawCode === "spend_limit_exceeded" ? rawCode : "billing_required",
      message: userSafeMessage(rawMessage) ?? ERROR_SEMANTICS.payment_required.message,
      retryable: false,
    };
  }
  if (status === 429 && rawCode === "concurrency_limit_reached") {
    return {
      code: "concurrency_limit_reached",
      message: userSafeMessage(rawMessage) ?? overrides.concurrencyLimitFallback,
      retryable: true,
    };
  }
  if (status === 400 || status === 422) {
    return {
      code: "invalid_request",
      message: userSafeMessage(rawMessage) ?? ERROR_SEMANTICS.bad_request.message,
      retryable: false,
    };
  }

  // Status-only resolution is for 4xx, never 5xx. The \`statuses\` lists OVERLAP in the 500
  // range — 500 is in \`internal_error\` and \`upstream_failed\`; 502 in \`upstream_failed\`,
  // \`upstream_unreachable\` and \`invalid_upstream_response\`; 503 in six — so with no code to
  // disambiguate, \`semanticsForStatus\` returns whichever key was DECLARED FIRST. That is
  // table order, not a decision. Measured 2026-09-18: a bodiless 502 answered \`upstream_failed\`
  // and a 504 answered \`http_504\`. A coded 5xx is unaffected; the \`rawCode\` branch above
  // resolves it before this point.
  const recognised = !rawCode || isKnownErrorCode(rawCode);
  const byStatus = recognised && status < 500 ? semanticsForStatus(status) : undefined;
  if (byStatus) {
    // 503 answers \`service_unavailable\` rather than the contract's \`unavailable\`: the outward
    // name both surfaces have always published for a busy service. The contract owns the COPY.
    return {
      code: status === 503 ? "service_unavailable" : defaultCodeForStatus(status),
      message: byStatus.message,
      retryable: byStatus.retryable,
    };
  }
  if (status >= 500) {
    return { code: "service_unavailable", message: ERROR_SEMANTICS.unavailable.message, retryable: true };
  }
  return {
    code: status === 0 && rawCode === "network_error" ? "network_error" : "request_failed",
    message: userSafeMessage(rawMessage) ?? overrides.requestFailedFallback,
    retryable: status === 0 || status >= 500,
  };
}
`;

const path = new URL("../libs/http-client/src/generated/error-semantics.ts", import.meta.url);

if (process.argv.includes("--check")) {
  const current = await readFile(path, "utf8").catch(() => null);
  if (current !== body) throw new Error("error-semantics generated source is stale; run npm run spec:types");
  console.log(`Error semantics verified against OpenAPI: ${Object.keys(codes).length} codes, ${uncopied.length} uncopied`);
} else {
  await writeFile(path, body);
  console.log(`Error semantics materialized from OpenAPI: ${Object.keys(codes).length} codes, ${uncopied.length} uncopied`);
}
